//! Structured UCI operations for OpenWrt configuration.
//!
//! # Go v1 vs Rust comparison
//!
//! Go v1 uses raw `os/exec` commands for all UCI operations:
//! ```go
//! exec.Command("uci", "set", "wireless.radio0.disabled=0").Run()
//! ```
//!
//! Rust uses typed operations that render to multiple transports:
//! - Shell: `uci set wireless.radio0.disabled='0'`
//! - ubus HTTP: JSON-RPC to rpcd
//!
//! This pattern is inspired by conwrt's transport-agnostic Op types.
//! Benefits over Go:
//! - Testable: mock the transport, verify the ops
//! - Safe: structured quoting prevents shell injection
//! - Flexible: switch transport without changing business logic
//! - Dual transport: SSH shell OR ubus HTTP (Go only has shell)

use std::process::Stdio;

/// Shell-safe quoting for UCI values.
///
/// Wraps a value in single quotes, escaping any embedded single quotes
/// by replacing `'` with `'\''`. This prevents shell injection when values
/// are passed to uci commands.
///
/// Go v1 does NOT do this — values are concatenated directly into commands.
///
/// # Examples
/// ```
/// use tollgate_net::v1::server::uci_ops::sh_quote;
/// assert_eq!(sh_quote("hello"), "'hello'");
/// assert_eq!(sh_quote("it's"), "'it'\\''s'");
/// ```
pub fn sh_quote(value: &str) -> String {
    let escaped = value.replace('\'', "'\\''");
    format!("'{escaped}'")
}

/// Validate a value is safe for use as a UCI section/interface name.
///
/// Only alphanumeric characters, underscores, hyphens, dots, and `@[]`
/// indices (e.g. `@wifi-iface[0]`) are allowed. Rejects anything that
/// could be interpreted as a shell metacharacter.
pub fn validate_identifier(name: &str) -> Result<(), UciOpError> {
    if name.is_empty() {
        return Err(UciOpError::InvalidIdentifier("empty identifier".to_owned()));
    }
    for ch in name.chars() {
        match ch {
            'a'..='z' | 'A'..='Z' | '0'..='9' | '_' | '-' | '.' | '@' | '[' | ']' => {}
            _ => {
                return Err(UciOpError::InvalidIdentifier(format!(
                    "invalid character '{ch}' in identifier"
                )));
            }
        }
    }
    Ok(())
}

/// A single value — string or list of strings (for UCI list options).
#[derive(Debug, Clone, PartialEq)]
pub enum OpValue {
    /// Single scalar value.
    Single(String),
    /// UCI list option (multiple values for one key).
    List(Vec<String>),
}

/// Structured UCI operations.
///
/// Each variant represents one atomic configuration action.
/// Operations are generated by business logic, then rendered to
/// a target transport (shell or ubus) by a renderer.
#[derive(Debug, Clone, PartialEq)]
pub enum UciOp {
    /// Set one or more options on a UCI section.
    /// Shell: `uci set {config}.{section}.{key}='{value}'`
    /// ubus: `uci.set {config, section, values}`
    Set {
        config: String,
        section: String,
        values: Vec<(String, OpValue)>,
    },

    /// Add a new named or anonymous UCI section.
    /// Shell: `uci set {config}.{name}='{type}'` then set values
    /// ubus: `uci.add {config, type, name, values}`
    Add {
        config: String,
        type_name: String,
        name: String,
        values: Vec<(String, OpValue)>,
    },

    /// Delete a section or specific option.
    /// Shell: `uci delete {config}.{section}` or `uci delete {config}.{section}.{option}`
    /// ubus: `uci.delete {config, section, option?}`
    Delete {
        config: String,
        section: String,
        option: Option<String>,
    },

    /// Append to a UCI list option.
    /// Shell: `uci add_list {config}.{section}.{option}='{value}'`
    /// ubus: `uci.set` with array value
    AddList {
        config: String,
        section: String,
        option: String,
        value: String,
    },

    /// Commit pending changes.
    /// Shell: `uci commit {config}`
    /// ubus: `uci.commit {config}`
    Commit { config: String },

    /// Raw shell command (for operations that don't map to UCI).
    /// ubus transport: skipped or mapped to ubus exec if available.
    Shell { command: String },

    /// Service management action.
    /// Shell: `/etc/init.d/{name} {action}`
    /// ubus: `rc.{action} {name}`
    Service { name: String, action: ServiceAction },

    /// Comment (for logging, not executed).
    Comment { text: String },
}

/// Service management actions (start, stop, restart, enable, disable).
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ServiceAction {
    Start,
    Stop,
    Restart,
    Enable,
    Disable,
}

impl std::fmt::Display for ServiceAction {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Start => write!(f, "start"),
            Self::Stop => write!(f, "stop"),
            Self::Restart => write!(f, "restart"),
            Self::Enable => write!(f, "enable"),
            Self::Disable => write!(f, "disable"),
        }
    }
}

/// Errors from UCI operations.
#[derive(Debug, thiserror::Error)]
pub enum UciOpError {
    /// Invalid identifier (section/option name contains disallowed characters).
    #[error("invalid identifier: {0}")]
    InvalidIdentifier(String),
    /// Shell command execution failed.
    #[error("shell command failed: {0}")]
    ShellFailed(String),
    /// ubus transport error.
    #[error("ubus error: {0}")]
    UbusError(String),
}

/// Render a list of ops to shell command strings.
///
/// Converts each [`UciOp`] variant to one or more shell command strings
/// suitable for execution via SSH or local shell. Comments are prefixed
/// with `#` and are not executed.
///
/// # Panics
/// Never panics — all variants produce valid output.
pub fn render_shell(ops: &[UciOp]) -> Vec<String> {
    let mut cmds = Vec::new();
    for op in ops {
        match op {
            UciOp::Set {
                config,
                section,
                values,
            } => {
                for (key, value) in values {
                    match value {
                        OpValue::Single(v) => {
                            cmds.push(format!("uci set {config}.{section}.{key}={}", sh_quote(v)));
                        }
                        OpValue::List(items) => {
                            // For lists, first delete existing, then add each item
                            cmds.push(format!(
                                "uci delete {config}.{section}.{key} 2>/dev/null || true"
                            ));
                            for item in items {
                                cmds.push(format!(
                                    "uci add_list {config}.{section}.{key}={}",
                                    sh_quote(item)
                                ));
                            }
                        }
                    }
                }
            }
            UciOp::Add {
                config,
                type_name,
                name,
                values,
            } => {
                // Named section: `uci set config.name='type'`
                if name.is_empty() {
                    cmds.push(format!("uci add {config} {type_name}"));
                } else {
                    cmds.push(format!("uci set {config}.{name}={}", sh_quote(type_name)));
                }
                for (key, value) in values {
                    let section_ref = if name.is_empty() {
                        // For anonymous sections, refer to the last added section
                        format!("@{type_name}[-1]")
                    } else {
                        name.clone()
                    };
                    match value {
                        OpValue::Single(v) => {
                            cmds.push(format!(
                                "uci set {config}.{section_ref}.{key}={}",
                                sh_quote(v)
                            ));
                        }
                        OpValue::List(items) => {
                            for item in items {
                                cmds.push(format!(
                                    "uci add_list {config}.{section_ref}.{key}={}",
                                    sh_quote(item)
                                ));
                            }
                        }
                    }
                }
            }
            UciOp::Delete {
                config,
                section,
                option,
            } => {
                if let Some(opt) = option {
                    cmds.push(format!("uci delete {config}.{section}.{opt}"));
                } else {
                    cmds.push(format!("uci delete {config}.{section}"));
                }
            }
            UciOp::AddList {
                config,
                section,
                option,
                value,
            } => {
                cmds.push(format!(
                    "uci add_list {config}.{section}.{option}={}",
                    sh_quote(value)
                ));
            }
            UciOp::Commit { config } => {
                cmds.push(format!("uci commit {config}"));
            }
            UciOp::Shell { command } => {
                cmds.push(command.clone());
            }
            UciOp::Service { name, action } => {
                cmds.push(format!("/etc/init.d/{name} {action}"));
            }
            UciOp::Comment { text } => {
                cmds.push(format!("# {text}"));
            }
        }
    }
    cmds
}

/// Execute ops via shell (`tokio::process::Command`).
///
/// Each command is run sequentially. Failed commands are logged but don't
/// stop execution — all ops are attempted. This matches Go v1's behavior
/// where a failed `uci set` doesn't prevent subsequent commands.
///
/// Returns a result per op (not per shell command — a single op may
/// produce multiple shell commands; the first failure is reported).
pub async fn execute_shell(ops: &[UciOp]) -> Vec<Result<(), UciOpError>> {
    let cmds = render_shell(ops);
    let mut results = Vec::with_capacity(ops.len());

    // Map each command back to its originating op index.
    // We iterate ops and track which commands belong to which op.
    let mut cmd_idx = 0usize;
    for op in ops {
        let op_cmds = render_shell(std::slice::from_ref(op));
        let mut op_result = Ok(());

        for _ in &op_cmds {
            if cmd_idx >= cmds.len() {
                break;
            }
            let cmd = &cmds[cmd_idx];
            cmd_idx += 1;

            // Skip comments (they start with '# ')
            if cmd.starts_with("# ") {
                continue;
            }

            tracing::debug!("executing: {cmd}");

            let output = tokio::process::Command::new("sh")
                .arg("-c")
                .arg(cmd)
                .stdout(Stdio::piped())
                .stderr(Stdio::piped())
                .output()
                .await;

            match output {
                Ok(out) if out.status.success() => {}
                Ok(out) => {
                    let stderr = String::from_utf8_lossy(&out.stderr);
                    tracing::warn!("command failed: {cmd}: {stderr}");
                    if op_result.is_ok() {
                        op_result = Err(UciOpError::ShellFailed(format!("{cmd}: {stderr}")));
                    }
                }
                Err(e) => {
                    tracing::warn!("command execution error: {cmd}: {e}");
                    if op_result.is_ok() {
                        op_result = Err(UciOpError::ShellFailed(format!("{cmd}: {e}")));
                    }
                }
            }
        }

        results.push(op_result);
    }

    results
}

/// Convenience builder for UCI operations.
///
/// Provides a fluent API for constructing a list of [`UciOp`] values.
///
/// # Examples
/// ```
/// use tollgate_net::v1::server::uci_ops::{UciOpBuilder, ServiceAction};
///
/// let ops = UciOpBuilder::new()
///     .set("wireless", "radio0", vec![("disabled", "0")])
///     .commit("wireless")
///     .service("network", ServiceAction::Restart)
///     .build();
///
/// assert_eq!(ops.len(), 3);
/// ```
pub struct UciOpBuilder {
    ops: Vec<UciOp>,
}

impl UciOpBuilder {
    /// Create a new empty builder.
    #[must_use]
    pub fn new() -> Self {
        Self { ops: Vec::new() }
    }

    /// Set one or more key-value pairs on a UCI section.
    #[must_use]
    pub fn set(mut self, config: &str, section: &str, values: Vec<(&str, &str)>) -> Self {
        self.ops.push(UciOp::Set {
            config: config.to_owned(),
            section: section.to_owned(),
            values: values
                .into_iter()
                .map(|(k, v)| (k.to_owned(), OpValue::Single(v.to_owned())))
                .collect(),
        });
        self
    }

    /// Add a new UCI section with optional initial values.
    #[must_use]
    pub fn add(
        mut self,
        config: &str,
        type_name: &str,
        name: &str,
        values: Vec<(&str, &str)>,
    ) -> Self {
        self.ops.push(UciOp::Add {
            config: config.to_owned(),
            type_name: type_name.to_owned(),
            name: name.to_owned(),
            values: values
                .into_iter()
                .map(|(k, v)| (k.to_owned(), OpValue::Single(v.to_owned())))
                .collect(),
        });
        self
    }

    /// Delete an entire UCI section.
    #[must_use]
    pub fn delete(mut self, config: &str, section: &str) -> Self {
        self.ops.push(UciOp::Delete {
            config: config.to_owned(),
            section: section.to_owned(),
            option: None,
        });
        self
    }

    /// Delete a specific option from a UCI section.
    #[must_use]
    pub fn delete_option(mut self, config: &str, section: &str, option: &str) -> Self {
        self.ops.push(UciOp::Delete {
            config: config.to_owned(),
            section: section.to_owned(),
            option: Some(option.to_owned()),
        });
        self
    }

    /// Append a value to a UCI list option.
    #[must_use]
    pub fn add_list(mut self, config: &str, section: &str, option: &str, value: &str) -> Self {
        self.ops.push(UciOp::AddList {
            config: config.to_owned(),
            section: section.to_owned(),
            option: option.to_owned(),
            value: value.to_owned(),
        });
        self
    }

    /// Commit pending changes for a config.
    #[must_use]
    pub fn commit(mut self, config: &str) -> Self {
        self.ops.push(UciOp::Commit {
            config: config.to_owned(),
        });
        self
    }

    /// Add a raw shell command.
    #[must_use]
    pub fn shell(mut self, command: &str) -> Self {
        self.ops.push(UciOp::Shell {
            command: command.to_owned(),
        });
        self
    }

    /// Add a service management action.
    #[must_use]
    pub fn service(mut self, name: &str, action: ServiceAction) -> Self {
        self.ops.push(UciOp::Service {
            name: name.to_owned(),
            action,
        });
        self
    }

    /// Add a comment (not executed).
    #[must_use]
    pub fn comment(mut self, text: &str) -> Self {
        self.ops.push(UciOp::Comment {
            text: text.to_owned(),
        });
        self
    }

    /// Build the final list of operations.
    #[must_use]
    pub fn build(self) -> Vec<UciOp> {
        self.ops
    }
}

impl Default for UciOpBuilder {
    fn default() -> Self {
        Self::new()
    }
}

